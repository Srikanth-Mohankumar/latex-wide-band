#!/usr/bin/env python3
"""Verify generic content-conservation promises in a wideband-cc stress PDF."""

from __future__ import annotations

import collections
import re
import subprocess
import sys
from pathlib import Path


def strip_comments(source: str) -> str:
    return re.sub(r"(?<!\\)%.*", "", source)


def extracted_text(pdf: Path) -> str:
    return subprocess.check_output(["pdftotext", str(pdf), "-"], text=True)


def page_count(pdf: Path) -> int:
    info = subprocess.check_output(["pdfinfo", str(pdf)], text=True)
    match = re.search(r"^Pages:\s+(\d+)\s*$", info, re.M)
    if not match:
        fail(f"{pdf.name}: pdfinfo did not report a page count")
    return int(match.group(1))


def extracted_page_text(pdf: Path, page: int) -> str:
    return subprocess.check_output(
        ["pdftotext", "-f", str(page), "-l", str(page), str(pdf), "-"],
        text=True,
    )


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    raise SystemExit(1)


if len(sys.argv) != 3:
    raise SystemExit("usage: check-cc-stress.py SOURCE.tex OUTPUT.pdf")

source_path = Path(sys.argv[1])
pdf_path = Path(sys.argv[2])
raw = source_path.read_text(encoding="utf-8")
body = strip_comments(raw.split(r"\begin{document}", 1)[-1])
text = extracted_text(pdf_path)

# Enforce an explicit "N pages" promise from the assertion banner when one is
# present. This is authored intent, not a value learned from current output.
header = raw.split(r"\begin{document}", 1)[0]
assertion = header.split("ASSERTION:", 1)[-1] if "ASSERTION:" in header else ""
page_promises = {int(n) for n in re.findall(r"\b(\d+)\s+pages\b", assertion)}
if len(page_promises) > 1:
    fail(f"{source_path.name}: conflicting page-count promises {sorted(page_promises)}")
if page_promises:
    expected_pages = next(iter(page_promises))
    rendered_pages = page_count(pdf_path)
    if rendered_pages != expected_pages:
        fail(f"{pdf_path.name}: {rendered_pages} page(s), expected {expected_pages}")

# An assertion such as "TOKEN begins page 2" pins an important placement
# decision without learning coordinates from the implementation under test.
for token, page_string in re.findall(
    r"([A-Z][A-Z0-9-]+)\s+begins\s+page\s+(\d+)", assertion
):
    promised_page = int(page_string)
    if token not in extracted_page_text(pdf_path, promised_page):
        fail(f"{pdf_path.name}: {token} did not begin page {promised_page}")
    for earlier_page in range(1, promised_page):
        if token in extracted_page_text(pdf_path, earlier_page):
            fail(
                f"{pdf_path.name}: {token} appeared on page {earlier_page}, "
                f"before promised page {promised_page}"
            )

# Every explicit \Par{token} call must survive exactly as often as it occurs in
# the source.  This catches the most common drop/duplication failures without
# hard-coding output generated by the implementation under test.
paragraphs = collections.Counter(re.findall(r"\\Par\{([^{}]+)\}", body))
for token, expected in sorted(paragraphs.items()):
    rendered = text.count(f"[{token}]")
    if rendered != expected:
        fail(f"{pdf_path.name}: [{token}] rendered {rendered} time(s), expected {expected}")

# Stress labels deliberately contain a hyphen and uppercase letters.  Verify
# each literal label from the document body, including bands and float markers.
labels = collections.Counter(
    re.findall(r"(?<![A-Za-z0-9-])([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+)(?![A-Za-z0-9-])", body)
)
for token, expected in sorted(labels.items()):
    rendered = text.count(token)
    if rendered != expected:
        fail(f"{pdf_path.name}: {token} rendered {rendered} time(s), expected {expected}")

# Several regression sources state a body-word count explicitly because a
# surviving paragraph tag alone cannot detect truncation at the page boundary.
for expected in map(int, re.findall(r'["“]minim["”]\s+(?:appears\s+)?(\d+)\s+times', raw, re.I)):
    rendered = len(re.findall(r"\bminim\b", text, re.I))
    if rendered != expected:
        fail(f"{pdf_path.name}: minim rendered {rendered} time(s), expected {expected}")

if "??" in text:
    fail(f"{pdf_path.name}: unresolved reference marker (??) found")

print(
    f"ok  {pdf_path.name}: {sum(paragraphs.values())} paragraph token(s), "
    f"{sum(labels.values())} labelled marker(s) conserved"
)
